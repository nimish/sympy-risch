def _polynomial_ring(
    extension: AlgebraicExtension,
) -> tuple[FractionField, Domain, Symbol, Domain]:
    parent, constants, variable = _base_polynomial_ring(extension)
    return parent, constants, variable, constants.poly_ring(variable)


def _polynomial_coordinates(
    coordinates: tuple[FracElement, ...],
    extension: AlgebraicExtension,
) -> tuple[Poly, ...]:
    parent, constants, variable = _base_polynomial_ring(extension)
    return tuple(
        _parent_element_polynomial(
            coordinate,
            parent,
            constants,
            variable,
        )
        for coordinate in coordinates
    )


def _matrix_columns(matrix: DomainMatrix) -> tuple[tuple[object, ...], ...]:
    rows = matrix.to_list()
    return tuple(
        tuple(rows[row][column] for row in range(matrix.shape[0]))
        for column in range(matrix.shape[1])
    )


def _matrix_from_columns(
    columns: tuple[tuple[object, ...], ...],
    domain: Domain,
) -> DomainMatrix:
    if not columns:
        raise ValueError("a full-rank lattice needs at least one generator")
    row_count = len(columns[0])
    if any(len(column) != row_count for column in columns):
        raise ValueError("lattice-generator columns have inconsistent lengths")
    return DomainMatrix(
        [
            [domain.convert(columns[column][row]) for column in range(len(columns))]
            for row in range(row_count)
        ],
        (row_count, len(columns)),
        domain,
    )


def _row_lattice_basis(
    rows: tuple[tuple[FracElement, ...], ...],
    extension: AlgebraicExtension,
) -> tuple[tuple[FracElement, ...], ...]:
    r"""Return a basis of the ``C[x]`` row module generated by ``rows``."""
    if not rows:
        raise ValueError("a full-rank lattice needs at least one generator")

    parent, constants, variable, polynomial_ring = _polynomial_ring(extension)
    rank = extension.field.rank
    if any(len(row) != rank for row in rows):
        raise ValueError("lattice generators have the wrong coordinate length")

    entries = tuple(entry for row in rows for entry in row)
    denominator = _common_denominator(entries, constants, variable)
    denominator_element = _polynomial_parent_element(denominator, parent)
    polynomial_rows = [
        [
            polynomial_ring.from_sympy(
                _parent_element_polynomial(
                    entry * denominator_element,
                    parent,
                    constants,
                    variable,
                ).as_expr()
            )
            for entry in row
        ]
        for row in rows
    ]
    generator_matrix = DomainMatrix(
        polynomial_rows,
        (len(rows), rank),
        polynomial_ring,
    )
    _, left_transform, _ = smith_normal_decomp(generator_matrix)
    reduced_rows = [
        row
        for row in (left_transform * generator_matrix).to_list()
        if any(coefficient != polynomial_ring.zero for coefficient in row)
    ]
    if len(reduced_rows) != rank:
        raise ValueError("lattice generators do not have full field rank")

    return tuple(
        tuple(
            _polynomial_parent_element(
                Poly(
                    polynomial_ring.to_sympy(coefficient),
                    variable,
                    domain=constants,
                ),
                parent,
            )
            / denominator_element
            for coefficient in row
        )
        for row in reduced_rows
    )


def _column_lattice_basis(
    columns: tuple[tuple[FracElement, ...], ...],
    extension: AlgebraicExtension,
) -> DomainMatrix:
    """Return a square column-basis matrix for a full-rank lattice."""
    basis_vectors = _row_lattice_basis(columns, extension)
    parent = extension.parent_field
    return _matrix_from_columns(
        cast(tuple[tuple[object, ...], ...], basis_vectors),
        parent,
    )


def _integrality_lattice(
    matrix: DomainMatrix,
    extension: AlgebraicExtension,
) -> DomainMatrix:
    r"""Compute ``{u in C(x)^n : matrix*u in C[x]^m}``.

    A Smith decomposition of a common-denominator multiple ``P`` gives
    ``D = U*P*V``.  Writing ``u = V*w`` reduces the condition to
    ``D*w`` being divisible by the common denominator, one diagonal entry at
    a time.
    """
    parent, constants, variable, polynomial_ring = _polynomial_ring(extension)
    if matrix.domain != parent:
        matrix = matrix.convert_to(parent)
    row_count, column_count = matrix.shape
    if column_count != extension.field.rank:
        raise ValueError("integrality constraints have the wrong field rank")

    entries = tuple(
        cast(FracElement, entry) for row in matrix.to_list() for entry in row
    )
    denominator = _common_denominator(entries, constants, variable)
    denominator_element = _polynomial_parent_element(denominator, parent)
    polynomial_matrix = DomainMatrix(
        [
            [
                polynomial_ring.from_sympy(
                    _parent_element_polynomial(
                        cast(FracElement, entry) * denominator_element,
                        parent,
                        constants,
                        variable,
                    ).as_expr()
                )
                for entry in row
            ]
            for row in matrix.to_list()
        ],
        (row_count, column_count),
        polynomial_ring,
    )
    diagonal, _, right_transform = smith_normal_decomp(polynomial_matrix)
    diagonal_rows = diagonal.to_list()
    right_rows = right_transform.to_list()
    diagonal_entries = tuple(
        diagonal_rows[index][index] for index in range(column_count)
    )
    if any(entry == polynomial_ring.zero for entry in diagonal_entries):
        raise ValueError("integrality constraints do not have full column rank")

    columns: list[tuple[FracElement, ...]] = []
    for column, diagonal_entry in enumerate(diagonal_entries):
        diagonal_polynomial = Poly(
            polynomial_ring.to_sympy(diagonal_entry),
            variable,
            domain=constants,
        )
        diagonal_parent = _polynomial_parent_element(
            diagonal_polynomial,
            parent,
        )
        scale = denominator_element / diagonal_parent
        columns.append(
            tuple(
                parent.convert(polynomial_ring.to_sympy(right_rows[row][column]))
                * scale
                for row in range(column_count)
            )
        )
    return _matrix_from_columns(tuple(columns), parent)


def _matrix_entries_are_polynomial(
    matrix: DomainMatrix,
    extension: AlgebraicExtension,
) -> bool:
    try:
        for column in _matrix_columns(matrix):
            _polynomial_coordinates(
                cast(tuple[FracElement, ...], column),
                extension,
            )
    except ValueError:
        return False
    return True


@dataclass(frozen=True, slots=True, eq=False)
class AlgebraicOrder:
    r"""A certified full-rank ``C[x]`` order in an algebraic function field."""

    basis: IntegralBasis

    def __post_init__(self) -> None:
        extension = self.extension
        parent = extension.parent_field
        try:
            _polynomial_coordinates(
                self.basis.coordinates(extension.field.one),
                extension,
            )
        except ValueError as exc:
            raise ValueError("an algebraic order must contain one") from exc

        for left in self.basis.elements:
            for right in self.basis.elements:
                try:
                    _polynomial_coordinates(
                        self.basis.coordinates(left * right),
                        extension,
                    )
                except ValueError as exc:
                    raise ValueError(
                        "the supplied basis is not closed under multiplication"
                    ) from exc
        if not parent.is_Field:
            raise ValueError("an algebraic order requires a fraction-field parent")

    @property
    def extension(self) -> AlgebraicExtension:
        """The fraction field represented by this order."""
        return self.basis.extension

    @property
    def rank(self) -> int:
        """Rank over the polynomial coefficient ring."""
        return len(self.basis.elements)

    def coordinates(self, element: object) -> tuple[FracElement, ...]:
        """Return coordinates in the order basis."""
        return self.basis.coordinates(element)

    def polynomial_coordinates(self, element: object) -> tuple[Poly, ...]:
        """Return polynomial coordinates, rejecting elements outside the order."""
        return _polynomial_coordinates(
            self.coordinates(element),
            self.extension,
        )

    def contains(self, element: object) -> bool:
        """Whether ``element`` belongs to this ``C[x]`` order."""
        try:
            self.polynomial_coordinates(element)
        except ValueError:
            return False
        return True

    def multiplication_matrix(self, element: object) -> DomainMatrix:
        """Matrix of multiplication in the selected order basis."""
        parent = self.extension.parent_field
        columns = tuple(
            self.coordinates(
                _extension_element(self.extension, element) * basis_element
            )
            for basis_element in self.basis.elements
        )
        return _matrix_from_columns(
            cast(tuple[tuple[object, ...], ...], columns),
            parent,
        )

    def trace_pairing_matrix(self) -> DomainMatrix:
        """Trace-pairing matrix over ``C[x]``."""
        _, constants, variable, polynomial_ring = _polynomial_ring(self.extension)
        parent_matrix = self.extension.trace_pairing_matrix(
            cast(tuple[object, ...], self.basis.elements)
        )
        return DomainMatrix(
            [
                [
                    polynomial_ring.from_sympy(
                        _parent_element_polynomial(
                            cast(FracElement, entry),
                            cast(FractionField, self.extension.parent_field),
                            constants,
                            variable,
                        ).as_expr()
                    )
                    for entry in row
                ]
                for row in parent_matrix.to_list()
            ],
            (self.rank, self.rank),
            polynomial_ring,
        )

    @property
    def discriminant(self) -> Poly:
        """Discriminant of this order basis."""
        _, constants, variable, polynomial_ring = _polynomial_ring(self.extension)
        determinant = self.trace_pairing_matrix().det()
        return Poly(
            polynomial_ring.to_sympy(determinant),
            variable,
            domain=constants,
        )

    def equivalent(self, other: AlgebraicOrder) -> bool:
        """Whether two bases span the same polynomial order."""
        if self.extension != other.extension:
            return False
        return all(self.contains(element) for element in other.basis.elements) and all(
            other.contains(element) for element in self.basis.elements
        )

    def contains_order(self, other: AlgebraicOrder) -> bool:
        """Whether ``other`` is a suborder of this order."""
        if self.extension != other.extension:
            return False
        return all(self.contains(element) for element in other.basis.elements)

    def index_of(self, suborder: AlgebraicOrder) -> Poly:
        r"""Return the determinant ideal ``[self : suborder]``."""
        if not self.contains_order(suborder):
            raise ValueError("the supplied order is not a suborder")
        _, constants, variable = _base_polynomial_ring(self.extension)
        parent = self.extension.parent_field
        coordinate_matrix = _matrix_from_columns(
            cast(
                tuple[tuple[object, ...], ...],
                tuple(self.coordinates(element) for element in suborder.basis.elements),
            ),
            parent,
        )
        determinant = cast(FracElement, coordinate_matrix.det())
        index = _parent_element_polynomial(
            determinant,
            cast(FractionField, parent),
            constants,
            variable,
        )
        return index.monic()

    def unit_ideal(self) -> AlgebraicFractionalIdeal:
        """Return the unit ideal."""
        return AlgebraicFractionalIdeal(self, self.basis.elements)

    def fractional_ideal(
        self,
        generators: tuple[object, ...],
    ) -> AlgebraicFractionalIdeal:
        """Return the full-rank fractional ideal generated as an order ideal."""
        expanded = tuple(
            _extension_element(self.extension, generator) * basis_element
            for generator in generators
            for basis_element in self.basis.elements
        )
        return AlgebraicFractionalIdeal(self, expanded)

    def principal_ideal(self, generator: object) -> AlgebraicFractionalIdeal:
        """Return the nonzero principal fractional ideal ``generator*self``."""
        element = _extension_element(self.extension, generator)
        if element == self.extension.field.zero:
            raise ValueError("the zero element does not define a fractional ideal")
        return AlgebraicFractionalIdeal(
            self,
            tuple(element * basis_element for basis_element in self.basis.elements),
        )

    def trace_radical(self, prime: Poly) -> AlgebraicFractionalIdeal:
        r"""Return the trace radical of this order modulo ``prime``."""
        context = _BaseResidueContext.create(self.extension, prime)
        trace_matrix = self.trace_pairing_matrix()
        residue_matrix = DomainMatrix(
            [
                [
                    context.reduce_polynomial(
                        Poly(
                            trace_matrix.domain.to_sympy(entry),
                            context.prime.gens[0],
                            domain=context.prime.domain,
                        )
                    )
                    for entry in row
                ]
                for row in trace_matrix.to_list()
            ],
            trace_matrix.shape,
            context.field,
        )
        kernel_rows = residue_matrix.nullspace().to_list()
        prime_element = _embed_parent(self.extension, context.prime)
        generators: list[ExtensionElement] = [
            prime_element * basis_element for basis_element in self.basis.elements
        ]
        for kernel_row in kernel_rows:
            generators.append(
                self.basis.element(
                    tuple(
                        _polynomial_parent_element(
                            context.lift(coefficient),
                            cast(
                                FractionField,
                                self.extension.parent_field,
                            ),
                        )
                        for coefficient in kernel_row
                    )
                )
            )
        return AlgebraicFractionalIdeal(self, tuple(generators))

    def idealizer(
        self,
        ideal: AlgebraicFractionalIdeal,
    ) -> AlgebraicOrder:
        """Return ``{a in L : a*ideal is contained in ideal}``."""
        if ideal.order is not self:
            raise ValueError("the idealizer requires an ideal of this order")
        quotient = ideal.colon(ideal)
        return AlgebraicOrder(IntegralBasis(self.extension, quotient.basis_elements))

    @property
    def codifferent(self) -> AlgebraicFractionalIdeal:
        r"""Return ``{a : Tr(a*self) is contained in C[x]}``."""
        parent = self.extension.parent_field
        trace_parent = self.trace_pairing_matrix().convert_to(parent)
        try:
            coordinate_matrix = trace_parent.inv()
        except DMNonInvertibleMatrixError as exc:
            raise ValueError("the trace pairing is degenerate") from exc
        elements = tuple(
            self.basis.element(column) for column in _matrix_columns(coordinate_matrix)
        )
        return AlgebraicFractionalIdeal(self, elements)

    @property
    def different(self) -> AlgebraicFractionalIdeal:
        """Return the complementary different ideal."""
        return self.codifferent.inverse()


@dataclass(frozen=True, slots=True, eq=False)
class AlgebraicFractionalIdeal:
    r"""A nonzero full-rank fractional ideal of an ``AlgebraicOrder``."""

    order: AlgebraicOrder
    basis_elements: tuple[ExtensionElement, ...]
    _coordinate_matrix: DomainMatrix = dataclass_field(
        init=False,
        repr=False,
        compare=False,
    )
    _coordinate_inverse: DomainMatrix = dataclass_field(
        init=False,
        repr=False,
        compare=False,
    )

    def __post_init__(self) -> None:
        extension = self.order.extension
        coerced = tuple(
            _extension_element(extension, element) for element in self.basis_elements
        )
        if not coerced:
            raise ValueError("a fractional ideal needs nonzero generators")
        rows = tuple(self.order.coordinates(element) for element in coerced)
        basis_rows = _row_lattice_basis(rows, extension)
        basis_elements = tuple(
            self.order.basis.element(cast(tuple[object, ...], row))
            for row in basis_rows
        )
        coordinate_matrix = _matrix_from_columns(
            cast(tuple[tuple[object, ...], ...], basis_rows),
            extension.parent_field,
        )
        try:
            coordinate_inverse = coordinate_matrix.inv()
        except DMNonInvertibleMatrixError as exc:
            raise ValueError("fractional-ideal generators are not full rank") from exc

        object.__setattr__(self, "basis_elements", basis_elements)
        object.__setattr__(self, "_coordinate_matrix", coordinate_matrix)
        object.__setattr__(self, "_coordinate_inverse", coordinate_inverse)

        for order_element in self.order.basis.elements:
            for ideal_element in basis_elements:
                if not self.contains(order_element * ideal_element):
                    raise ValueError(
                        "the generated lattice is not stable under the order"
                    )

    @property
    def coordinate_matrix(self) -> DomainMatrix:
        """Columns of the ideal basis in order coordinates."""
        return self._coordinate_matrix

    @property
    def is_integral(self) -> bool:
        """Whether this fractional ideal is contained in its order."""
        return _matrix_entries_are_polynomial(
            self._coordinate_matrix,
            self.order.extension,
        )

    @property
    def is_unit_ideal(self) -> bool:
        """Whether this is the whole order."""
        return self == self.order.unit_ideal()

    def coordinates(self, element: object) -> tuple[FracElement, ...]:
        """Coordinates of a field element in this ideal basis."""
        order_coordinates = self.order.coordinates(element)
        parent = self.order.extension.parent_field
        vector = DomainMatrix(
            [[coordinate] for coordinate in order_coordinates],
            (self.order.rank, 1),
            parent,
        )
        result = self._coordinate_inverse * vector
        return cast(
            tuple[FracElement, ...],
            tuple(row[0] for row in result.to_list()),
        )

    def contains(self, element: object) -> bool:
        """Whether the field element belongs to this ideal."""
        try:
            _polynomial_coordinates(
                self.coordinates(element),
                self.order.extension,
            )
        except ValueError:
            return False
        return True

    def is_subset_of(self, other: AlgebraicFractionalIdeal) -> bool:
        """Whether this ideal is contained in ``other``."""
        self._require_same_order(other)
        transition = other._coordinate_inverse * self._coordinate_matrix
        return _matrix_entries_are_polynomial(
            transition,
            self.order.extension,
        )

    def _require_same_order(self, other: AlgebraicFractionalIdeal) -> None:
        if not isinstance(other, AlgebraicFractionalIdeal):
            raise TypeError("fractional-ideal arithmetic needs another ideal")
        if other.order is not self.order:
            raise ValueError("fractional ideals must use the same order instance")

    def __eq__(self, other: object) -> bool:
        if not isinstance(other, AlgebraicFractionalIdeal):
            return NotImplemented
        if other.order is not self.order:
            return False
        return self.is_subset_of(other) and other.is_subset_of(self)

    def add(
        self,
        other: AlgebraicFractionalIdeal,
    ) -> AlgebraicFractionalIdeal:
        """Ideal sum."""
        self._require_same_order(other)
        return AlgebraicFractionalIdeal(
            self.order,
            self.basis_elements + other.basis_elements,
        )

    def multiply(
        self,
        other: AlgebraicFractionalIdeal,
    ) -> AlgebraicFractionalIdeal:
        """Ideal product."""
        self._require_same_order(other)
        return AlgebraicFractionalIdeal(
            self.order,
            tuple(
                left * right
                for left in self.basis_elements
                for right in other.basis_elements
            ),
        )

    def scale(self, element: object) -> AlgebraicFractionalIdeal:
        """Scale by a nonzero field element."""
        scalar = _extension_element(self.order.extension, element)
        if scalar == self.order.extension.field.zero:
            raise ValueError("a fractional ideal cannot be scaled by zero")
        return AlgebraicFractionalIdeal(
            self.order,
            tuple(scalar * basis_element for basis_element in self.basis_elements),
        )

    def power(self, exponent: int) -> AlgebraicFractionalIdeal:
        """Integral ideal power, including negative powers."""
        if not isinstance(exponent, int):
            raise TypeError("an ideal exponent must be an integer")
        if exponent == 0:
            return self.order.unit_ideal()
        if exponent < 0:
            return self.inverse().power(-exponent)
        result = self.order.unit_ideal()
        factor = self
        remaining = exponent
        while remaining:
            if remaining & 1:
                result = result.multiply(factor)
            remaining >>= 1
            if remaining:
                factor = factor.multiply(factor)
        return result

    def colon(
        self,
        other: AlgebraicFractionalIdeal,
    ) -> AlgebraicFractionalIdeal:
        r"""Return ``(self : other) = {a : a*other is contained in self}``."""
        self._require_same_order(other)
        constraints = []
        for other_element in other.basis_elements:
            multiplication = self.order.multiplication_matrix(other_element)
            constraints.extend((self._coordinate_inverse * multiplication).to_list())
        constraint_matrix = DomainMatrix(
            constraints,
            (len(constraints), self.order.rank),
            self.order.extension.parent_field,
        )
        coordinate_matrix = _integrality_lattice(
            constraint_matrix,
            self.order.extension,
        )
        return AlgebraicFractionalIdeal(
            self.order,
            tuple(
                self.order.basis.element(column)
                for column in _matrix_columns(coordinate_matrix)
            ),
        )

    def inverse(self) -> AlgebraicFractionalIdeal:
        """Fractional-ideal inverse with respect to the unit ideal."""
        return self.order.unit_ideal().colon(self)

    def intersection(
        self,
        other: AlgebraicFractionalIdeal,
    ) -> AlgebraicFractionalIdeal:
        """Module-theoretic intersection of two fractional ideals."""
        self._require_same_order(other)
        left_dual = self._coordinate_inverse.transpose()
        right_dual = other._coordinate_inverse.transpose()
        dual_sum = _column_lattice_basis(
            cast(
                tuple[tuple[FracElement, ...], ...],
                _matrix_columns(left_dual) + _matrix_columns(right_dual),
            ),
            self.order.extension,
        )
        intersection_matrix = dual_sum.inv().transpose()
        return AlgebraicFractionalIdeal(
            self.order,
            tuple(
                self.order.basis.element(column)
                for column in _matrix_columns(intersection_matrix)
            ),
        )

    def index_in(self, superideal: AlgebraicFractionalIdeal) -> Poly:
        """Determinant ideal of this ideal inside ``superideal``."""
        self._require_same_order(superideal)
        if not self.is_subset_of(superideal):
            raise ValueError("the ideal is not contained in the supplied ideal")
        transition = superideal._coordinate_inverse * self._coordinate_matrix
        determinant = cast(FracElement, transition.det())
        parent, constants, variable = _base_polynomial_ring(self.order.extension)
        return _parent_element_polynomial(
            determinant,
            parent,
            constants,
            variable,
        ).monic()
