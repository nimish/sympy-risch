def _polynomial_ring(
    extension: AlgebraicExtension,
) -> tuple[FractionField, Domain, Symbol, Domain]:
    parent, constants, variable = _base_polynomial_ring(extension)
    return parent, constants, variable, constants.poly_ring(variable)


def _polynomial_coordinates(
    coordinates: tuple[FracElement, ...],
    extension: AlgebraicExtension,
) -> tuple[Poly, ...]:
    parent, constants, variable = _base_polynomial_ring(extension)
    return tuple(
        _parent_element_polynomial(
            coordinate,
            parent,
            constants,
            variable,
        )
        for coordinate in coordinates
    )


def _matrix_columns(matrix: DomainMatrix) -> tuple[tuple[object, ...], ...]:
    rows = matrix.to_list()
    return tuple(
        tuple(rows[row][column] for row in range(matrix.shape[0]))
        for column in range(matrix.shape[1])
    )


def _matrix_from_columns(
    columns: tuple[tuple[object, ...], ...],
    domain: Domain,
) -> DomainMatrix:
    if not columns:
        raise ValueError("a full-rank lattice needs at least one generator")
    row_count = len(columns[0])
    if any(len(column) != row_count for column in columns):
        raise ValueError("lattice-generator columns have inconsistent lengths")
    return DomainMatrix(
        [
            [domain.convert(columns[column][row]) for column in range(len(columns))]
            for row in range(row_count)
        ],
        (row_count, len(columns)),
        domain,
    )


def _row_lattice_basis(
    rows: tuple[tuple[FracElement, ...], ...],
    extension: AlgebraicExtension,
) -> tuple[tuple[FracElement, ...], ...]:
    r"""Return a basis of the ``C[x]`` row module generated by ``rows``."""
    if not rows:
        raise ValueError("a full-rank lattice needs at least one generator")

    parent, constants, variable, polynomial_ring = _polynomial_ring(extension)
    rank = extension.field.rank
    if any(len(row) != rank for row in rows):
        raise ValueError("lattice generators have the wrong coordinate length")

    entries = tuple(entry for row in rows for entry in row)
    denominator = _common_denominator(entries, constants, variable)
    denominator_element = _polynomial_parent_element(denominator, parent)
    polynomial_rows = [
        [
            polynomial_ring.from_sympy(
                _parent_element_polynomial(
                    entry * denominator_element,
                    parent,
                    constants,
                    variable,
                ).as_expr()
            )
            for entry in row
        ]
        for row in rows
    ]
    generator_matrix = DomainMatrix(
        polynomial_rows,
        (len(rows), rank),
        polynomial_ring,
    )
    _, left_transform, _ = smith_normal_decomp(generator_matrix)
    reduced_rows = [
        row
        for row in (left_transform * generator_matrix).to_list()
        if any(coefficient != polynomial_ring.zero for coefficient in row)
    ]
    if len(reduced_rows) != rank:
        raise ValueError("lattice generators do not have full field rank")

    return tuple(
        tuple(
            _polynomial_parent_element(
                Poly(
                    polynomial_ring.to_sympy(coefficient),
                    variable,
                    domain=constants,
                ),
                parent,
            )
            / denominator_element
            for coefficient in row
        )
        for row in reduced_rows
    )


def _column_lattice_basis(
    columns: tuple[tuple[FracElement, ...], ...],
    extension: AlgebraicExtension,
) -> DomainMatrix:
    """Return a square column-basis matrix for a full-rank lattice."""
    basis_vectors = _row_lattice_basis(columns, extension)
    parent = extension.parent_field
    return _matrix_from_columns(
        cast(tuple[tuple[object, ...], ...], basis_vectors),
        parent,
    )


def _integrality_lattice(
    matrix: DomainMatrix,
    extension: AlgebraicExtension,
) -> DomainMatrix:
    r"""Compute ``{u in C(x)^n : matrix*u in C[x]^m}``.

    A Smith decomposition of a common-denominator multiple ``P`` gives
    ``D = U*P*V``.  Writing ``u = V*w`` reduces the condition to
    ``D*w`` being divisible by the common denominator, one diagonal entry at
    a time.
    """
    parent, constants, variable, polynomial_ring = _polynomial_ring(extension)
    if matrix.domain != parent:
        matrix = matrix.convert_to(parent)
    row_count, column_count = matrix.shape
    if column_count != extension.field.rank:
        raise ValueError("integrality constraints have the wrong field rank")

    entries = tuple(
        cast(FracElement, entry) for row in matrix.to_list() for entry in row
    )
    denominator = _common_denominator(entries, constants, variable)
    denominator_element = _polynomial_parent_element(denominator, parent)
    polynomial_matrix = DomainMatrix(
        [
            [
                polynomial_ring.from_sympy(
                    _parent_element_polynomial(
                        cast(FracElement, entry) * denominator_element,
                        parent,
                        constants,
                        variable,
                    ).as_expr()
                )
                for entry in row
            ]
            for row in matrix.to_list()
        ],
        (row_count, column_count),
        polynomial_ring,
    )
    diagonal, _, right_transform = smith_normal_decomp(polynomial_matrix)
    diagonal_rows = diagonal.to_list()
    right_rows = right_transform.to_list()
    diagonal_entries = tuple(
        diagonal_rows[index][index] for index in range(column_count)
    )
    if any(entry == polynomial_ring.zero for entry in diagonal_entries):
        raise ValueError("integrality constraints do not have full column rank")

    columns: list[tuple[FracElement, ...]] = []
    for column, diagonal_entry in enumerate(diagonal_entries):
        diagonal_polynomial = Poly(
            polynomial_ring.to_sympy(diagonal_entry),
            variable,
            domain=constants,
        )
        diagonal_parent = _polynomial_parent_element(
            diagonal_polynomial,
            parent,
        )
        scale = denominator_element / diagonal_parent
        columns.append(
            tuple(
                parent.convert(polynomial_ring.to_sympy(right_rows[row][column]))
                * scale
                for row in range(column_count)
            )
        )
    return _matrix_from_columns(tuple(columns), parent)


def _matrix_entries_are_polynomial(
    matrix: DomainMatrix,
    extension: AlgebraicExtension,
) -> bool:
    try:
        for column in _matrix_columns(matrix):
            _polynomial_coordinates(
                cast(tuple[FracElement, ...], column),
                extension,
            )
    except ValueError:
        return False
    return True


@dataclass(frozen=True, slots=True)
class _BaseResidueContext:
    """Exact reduction and lifting for one closed base point."""

    extension: AlgebraicExtension
    prime: Poly
    field: Domain
    root: Expr

    @classmethod
    def create(
        cls,
        extension: AlgebraicExtension,
        prime: Poly,
    ) -> _BaseResidueContext:
        normalized = _normalize_base_prime(extension, prime)
        _, constants, variable = _base_polynomial_ring(extension)
        algebraic_constants = _algebraic_constant_domain(constants)
        algebraic_prime = Poly(
            normalized.as_expr(),
            variable,
            domain=algebraic_constants,
        )
        if normalized.degree() == 1:
            root = cast(
                Expr,
                algebraic_constants.to_sympy(
                    algebraic_constants.convert(-algebraic_prime.nth(0))
                ),
            )
            return cls(extension, normalized, algebraic_constants, root)

        alias = Dummy(f"{variable.name}_bar")
        residue_field = algebraic_constants.alg_field_from_poly(
            algebraic_prime,
            alias=alias,
        )
        root = cast(AlgebraicNumber, residue_field.orig_ext[-1])
        return cls(extension, normalized, residue_field, root)

    def reduce_polynomial(self, polynomial: Poly) -> object:
        """Evaluate a base polynomial at the selected algebraic root."""
        _, constants, variable = _base_polynomial_ring(self.extension)
        normalized = Poly(
            polynomial.as_expr(),
            variable,
            domain=constants,
        )
        return self.field.from_sympy(normalized.as_expr().subs(variable, self.root))

    def lift(self, value: object) -> Poly:
        """Lift a residue-field element to degree below ``prime``."""
        _, constants, variable = _base_polynomial_ring(self.extension)
        converted = self.field.convert(value)
        expression = self.field.to_sympy(converted)
        if self.prime.degree() > 1:
            expression = expression.xreplace({self.root: variable})
        return Poly(
            expression,
            variable,
            domain=constants,
        ).rem(self.prime)


def _normalize_base_prime(
    extension: AlgebraicExtension,
    prime: Poly,
) -> Poly:
    if not isinstance(prime, Poly):
        raise TypeError("the base prime must be a SymPy Poly")
    _, constants, variable = _base_polynomial_ring(extension)
    if prime.gens != (variable,):
        raise ValueError(
            "the base prime generator must match the rational parent variable"
        )
    normalized = Poly(prime.as_expr(), variable, domain=constants)
    if normalized.degree() <= 0:
        raise ValueError("a finite base prime must be nonconstant")
    normalized = normalized.monic()
    if normalized.is_irreducible is not True:
        raise ValueError("a finite base prime must be irreducible")
    return normalized


@dataclass(frozen=True, slots=True, eq=False)
class AlgebraicOrder:
    r"""A certified full-rank ``C[x]`` order in an algebraic function field."""

    basis: IntegralBasis

    def __post_init__(self) -> None:
        extension = self.extension
        parent = extension.parent_field
        try:
            _polynomial_coordinates(
                self.basis.coordinates(extension.field.one),
                extension,
            )
        except ValueError as exc:
            raise ValueError("an algebraic order must contain one") from exc

        for left in self.basis.elements:
            for right in self.basis.elements:
                try:
                    _polynomial_coordinates(
                        self.basis.coordinates(left * right),
                        extension,
                    )
                except ValueError as exc:
                    raise ValueError(
                        "the supplied basis is not closed under multiplication"
                    ) from exc
        if not parent.is_Field:
            raise ValueError("an algebraic order requires a fraction-field parent")

    @property
    def extension(self) -> AlgebraicExtension:
        """The fraction field represented by this order."""
        return self.basis.extension

    @property
    def rank(self) -> int:
        """Rank over the polynomial coefficient ring."""
        return len(self.basis.elements)

    def coordinates(self, element: object) -> tuple[FracElement, ...]:
        """Return coordinates in the order basis."""
        return self.basis.coordinates(element)

    def polynomial_coordinates(self, element: object) -> tuple[Poly, ...]:
        """Return polynomial coordinates, rejecting elements outside the order."""
        return _polynomial_coordinates(
            self.coordinates(element),
            self.extension,
        )

    def contains(self, element: object) -> bool:
        """Whether ``element`` belongs to this ``C[x]`` order."""
        try:
            self.polynomial_coordinates(element)
        except ValueError:
            return False
        return True

    def multiplication_matrix(self, element: object) -> DomainMatrix:
        """Matrix of multiplication in the selected order basis."""
        parent = self.extension.parent_field
        columns = tuple(
            self.coordinates(
                _extension_element(self.extension, element) * basis_element
            )
            for basis_element in self.basis.elements
        )
        return _matrix_from_columns(
            cast(tuple[tuple[object, ...], ...], columns),
            parent,
        )

    def trace_pairing_matrix(self) -> DomainMatrix:
        """Trace-pairing matrix over ``C[x]``."""
        _, constants, variable, polynomial_ring = _polynomial_ring(self.extension)
        parent_matrix = self.extension.trace_pairing_matrix(
            cast(tuple[object, ...], self.basis.elements)
        )
        return DomainMatrix(
            [
                [
                    polynomial_ring.from_sympy(
                        _parent_element_polynomial(
                            cast(FracElement, entry),
                            cast(FractionField, self.extension.parent_field),
                            constants,
                            variable,
                        ).as_expr()
                    )
                    for entry in row
                ]
                for row in parent_matrix.to_list()
            ],
            (self.rank, self.rank),
            polynomial_ring,
        )

    @property
    def discriminant(self) -> Poly:
        """Discriminant of this order basis."""
        _, constants, variable, polynomial_ring = _polynomial_ring(self.extension)
        determinant = self.trace_pairing_matrix().det()
        return Poly(
            polynomial_ring.to_sympy(determinant),
            variable,
            domain=constants,
        )

    def equivalent(self, other: AlgebraicOrder) -> bool:
        """Whether two bases span the same polynomial order."""
        if self.extension != other.extension:
            return False
        return all(self.contains(element) for element in other.basis.elements) and all(
            other.contains(element) for element in self.basis.elements
        )

    def contains_order(self, other: AlgebraicOrder) -> bool:
        """Whether ``other`` is a suborder of this order."""
        if self.extension != other.extension:
            return False
        return all(self.contains(element) for element in other.basis.elements)

    def index_of(self, suborder: AlgebraicOrder) -> Poly:
        r"""Return the determinant ideal ``[self : suborder]``."""
        if not self.contains_order(suborder):
            raise ValueError("the supplied order is not a suborder")
        _, constants, variable = _base_polynomial_ring(self.extension)
        parent = self.extension.parent_field
        coordinate_matrix = _matrix_from_columns(
            cast(
                tuple[tuple[object, ...], ...],
                tuple(self.coordinates(element) for element in suborder.basis.elements),
            ),
            parent,
        )
        determinant = cast(FracElement, coordinate_matrix.det())
        index = _parent_element_polynomial(
            determinant,
            cast(FractionField, parent),
            constants,
            variable,
        )
        return index.monic()

    def unit_ideal(self) -> AlgebraicFractionalIdeal:
        """Return the unit ideal."""
        return AlgebraicFractionalIdeal(self, self.basis.elements)

    def fractional_ideal(
        self,
        generators: tuple[object, ...],
    ) -> AlgebraicFractionalIdeal:
        """Return the full-rank fractional ideal generated as an order ideal."""
        expanded = tuple(
            _extension_element(self.extension, generator) * basis_element
            for generator in generators
            for basis_element in self.basis.elements
        )
        return AlgebraicFractionalIdeal(self, expanded)

    def principal_ideal(self, generator: object) -> AlgebraicFractionalIdeal:
        """Return the nonzero principal fractional ideal ``generator*self``."""
        element = _extension_element(self.extension, generator)
        if element == self.extension.field.zero:
            raise ValueError("the zero element does not define a fractional ideal")
        return AlgebraicFractionalIdeal(
            self,
            tuple(element * basis_element for basis_element in self.basis.elements),
        )

    def trace_radical(self, prime: Poly) -> AlgebraicFractionalIdeal:
        r"""Return the trace radical of this order modulo ``prime``."""
        context = _BaseResidueContext.create(self.extension, prime)
        trace_matrix = self.trace_pairing_matrix()
        residue_matrix = DomainMatrix(
            [
                [
                    context.reduce_polynomial(
                        Poly(
                            trace_matrix.domain.to_sympy(entry),
                            context.prime.gens[0],
                            domain=context.prime.domain,
                        )
                    )
                    for entry in row
                ]
                for row in trace_matrix.to_list()
            ],
            trace_matrix.shape,
            context.field,
        )
        kernel_rows = residue_matrix.nullspace().to_list()
        prime_element = _embed_parent(self.extension, context.prime)
        generators: list[ExtensionElement] = [
            prime_element * basis_element for basis_element in self.basis.elements
        ]
        for kernel_row in kernel_rows:
            generators.append(
                self.basis.element(
                    tuple(
                        _polynomial_parent_element(
                            context.lift(coefficient),
                            cast(
                                FractionField,
                                self.extension.parent_field,
                            ),
                        )
                        for coefficient in kernel_row
                    )
                )
            )
        return AlgebraicFractionalIdeal(self, tuple(generators))

    def idealizer(
        self,
        ideal: AlgebraicFractionalIdeal,
    ) -> AlgebraicOrder:
        """Return ``{a in L : a*ideal is contained in ideal}``."""
        if ideal.order is not self:
            raise ValueError("the idealizer requires an ideal of this order")
        quotient = ideal.colon(ideal)
        return AlgebraicOrder(IntegralBasis(self.extension, quotient.basis_elements))

    @property
    def codifferent(self) -> AlgebraicFractionalIdeal:
        r"""Return ``{a : Tr(a*self) is contained in C[x]}``."""
        parent = self.extension.parent_field
        trace_parent = self.trace_pairing_matrix().convert_to(parent)
        try:
            coordinate_matrix = trace_parent.inv()
        except DMNonInvertibleMatrixError as exc:
            raise ValueError("the trace pairing is degenerate") from exc
        elements = tuple(
            self.basis.element(column) for column in _matrix_columns(coordinate_matrix)
        )
        return AlgebraicFractionalIdeal(self, elements)

    @property
    def different(self) -> AlgebraicFractionalIdeal:
        """Return the complementary different ideal."""
        return self.codifferent.inverse()


@dataclass(frozen=True, slots=True, eq=False)
class AlgebraicFractionalIdeal:
    r"""A nonzero full-rank fractional ideal of an ``AlgebraicOrder``."""

    order: AlgebraicOrder
    basis_elements: tuple[ExtensionElement, ...]
    _coordinate_matrix: DomainMatrix = dataclass_field(
        init=False,
        repr=False,
        compare=False,
    )
    _coordinate_inverse: DomainMatrix = dataclass_field(
        init=False,
        repr=False,
        compare=False,
    )

    def __post_init__(self) -> None:
        extension = self.order.extension
        coerced = tuple(
            _extension_element(extension, element) for element in self.basis_elements
        )
        if not coerced:
            raise ValueError("a fractional ideal needs nonzero generators")
        rows = tuple(self.order.coordinates(element) for element in coerced)
        basis_rows = _row_lattice_basis(rows, extension)
        basis_elements = tuple(
            self.order.basis.element(cast(tuple[object, ...], row))
            for row in basis_rows
        )
        coordinate_matrix = _matrix_from_columns(
            cast(tuple[tuple[object, ...], ...], basis_rows),
            extension.parent_field,
        )
        try:
            coordinate_inverse = coordinate_matrix.inv()
        except DMNonInvertibleMatrixError as exc:
            raise ValueError("fractional-ideal generators are not full rank") from exc

        object.__setattr__(self, "basis_elements", basis_elements)
        object.__setattr__(self, "_coordinate_matrix", coordinate_matrix)
        object.__setattr__(self, "_coordinate_inverse", coordinate_inverse)

        for order_element in self.order.basis.elements:
            for ideal_element in basis_elements:
                if not self.contains(order_element * ideal_element):
                    raise ValueError(
                        "the generated lattice is not stable under the order"
                    )

    @property
    def coordinate_matrix(self) -> DomainMatrix:
        """Columns of the ideal basis in order coordinates."""
        return self._coordinate_matrix

    @property
    def is_integral(self) -> bool:
        """Whether this fractional ideal is contained in its order."""
        return _matrix_entries_are_polynomial(
            self._coordinate_matrix,
            self.order.extension,
        )

    @property
    def is_unit_ideal(self) -> bool:
        """Whether this is the whole order."""
        return self == self.order.unit_ideal()

    def coordinates(self, element: object) -> tuple[FracElement, ...]:
        """Coordinates of a field element in this ideal basis."""
        order_coordinates = self.order.coordinates(element)
        parent = self.order.extension.parent_field
        vector = DomainMatrix(
            [[coordinate] for coordinate in order_coordinates],
            (self.order.rank, 1),
            parent,
        )
        result = self._coordinate_inverse * vector
        return cast(
            tuple[FracElement, ...],
            tuple(row[0] for row in result.to_list()),
        )

    def contains(self, element: object) -> bool:
        """Whether the field element belongs to this ideal."""
        try:
            _polynomial_coordinates(
                self.coordinates(element),
                self.order.extension,
            )
        except ValueError:
            return False
        return True

    def is_subset_of(self, other: AlgebraicFractionalIdeal) -> bool:
        """Whether this ideal is contained in ``other``."""
        self._require_same_order(other)
        transition = other._coordinate_inverse * self._coordinate_matrix
        return _matrix_entries_are_polynomial(
            transition,
            self.order.extension,
        )

    def _require_same_order(self, other: AlgebraicFractionalIdeal) -> None:
        if not isinstance(other, AlgebraicFractionalIdeal):
            raise TypeError("fractional-ideal arithmetic needs another ideal")
        if other.order is not self.order:
            raise ValueError("fractional ideals must use the same order instance")

    def __eq__(self, other: object) -> bool:
        if not isinstance(other, AlgebraicFractionalIdeal):
            return NotImplemented
        if other.order is not self.order:
            return False
        return self.is_subset_of(other) and other.is_subset_of(self)

    def add(
        self,
        other: AlgebraicFractionalIdeal,
    ) -> AlgebraicFractionalIdeal:
        """Ideal sum."""
        self._require_same_order(other)
        return AlgebraicFractionalIdeal(
            self.order,
            self.basis_elements + other.basis_elements,
        )

    def multiply(
        self,
        other: AlgebraicFractionalIdeal,
    ) -> AlgebraicFractionalIdeal:
        """Ideal product."""
        self._require_same_order(other)
        return AlgebraicFractionalIdeal(
            self.order,
            tuple(
                left * right
                for left in self.basis_elements
                for right in other.basis_elements
            ),
        )

    def scale(self, element: object) -> AlgebraicFractionalIdeal:
        """Scale by a nonzero field element."""
        scalar = _extension_element(self.order.extension, element)
        if scalar == self.order.extension.field.zero:
            raise ValueError("a fractional ideal cannot be scaled by zero")
        return AlgebraicFractionalIdeal(
            self.order,
            tuple(scalar * basis_element for basis_element in self.basis_elements),
        )

    def power(self, exponent: int) -> AlgebraicFractionalIdeal:
        """Integral ideal power, including negative powers."""
        if not isinstance(exponent, int):
            raise TypeError("an ideal exponent must be an integer")
        if exponent == 0:
            return self.order.unit_ideal()
        if exponent < 0:
            return self.inverse().power(-exponent)
        result = self.order.unit_ideal()
        factor = self
        remaining = exponent
        while remaining:
            if remaining & 1:
                result = result.multiply(factor)
            remaining >>= 1
            if remaining:
                factor = factor.multiply(factor)
        return result

    def colon(
        self,
        other: AlgebraicFractionalIdeal,
    ) -> AlgebraicFractionalIdeal:
        r"""Return ``(self : other) = {a : a*other is contained in self}``."""
        self._require_same_order(other)
        constraints = []
        for other_element in other.basis_elements:
            multiplication = self.order.multiplication_matrix(other_element)
            constraints.extend((self._coordinate_inverse * multiplication).to_list())
        constraint_matrix = DomainMatrix(
            constraints,
            (len(constraints), self.order.rank),
            self.order.extension.parent_field,
        )
        coordinate_matrix = _integrality_lattice(
            constraint_matrix,
            self.order.extension,
        )
        return AlgebraicFractionalIdeal(
            self.order,
            tuple(
                self.order.basis.element(column)
                for column in _matrix_columns(coordinate_matrix)
            ),
        )

    def inverse(self) -> AlgebraicFractionalIdeal:
        """Fractional-ideal inverse with respect to the unit ideal."""
        return self.order.unit_ideal().colon(self)

    def intersection(
        self,
        other: AlgebraicFractionalIdeal,
    ) -> AlgebraicFractionalIdeal:
        """Module-theoretic intersection of two fractional ideals."""
        self._require_same_order(other)
        left_dual = self._coordinate_inverse.transpose()
        right_dual = other._coordinate_inverse.transpose()
        dual_sum = _column_lattice_basis(
            cast(
                tuple[tuple[FracElement, ...], ...],
                _matrix_columns(left_dual) + _matrix_columns(right_dual),
            ),
            self.order.extension,
        )
        intersection_matrix = dual_sum.inv().transpose()
        return AlgebraicFractionalIdeal(
            self.order,
            tuple(
                self.order.basis.element(column)
                for column in _matrix_columns(intersection_matrix)
            ),
        )

    def index_in(self, superideal: AlgebraicFractionalIdeal) -> Poly:
        """Determinant ideal of this ideal inside ``superideal``."""
        self._require_same_order(superideal)
        if not self.is_subset_of(superideal):
            raise ValueError("the ideal is not contained in the supplied ideal")
        transition = superideal._coordinate_inverse * self._coordinate_matrix
        determinant = cast(FracElement, transition.det())
        parent, constants, variable = _base_polynomial_ring(self.order.extension)
        return _parent_element_polynomial(
            determinant,
            parent,
            constants,
            variable,
        ).monic()


@dataclass(frozen=True, slots=True)
class IntegralClosureStep:
    """One certified strict order enlargement."""

    prime: Poly
    previous_discriminant: Poly
    new_discriminant: Poly
    index: Poly
    previous_order: AlgebraicOrder
    new_order: AlgebraicOrder

    @property
    def verifies_discriminant_index_formula(self) -> bool:
        """Whether the monic discriminant ideals satisfy the index formula."""
        return (
            self.previous_discriminant.monic()
            == (self.new_discriminant * self.index**2).monic()
        )

    @property
    def verifies(self) -> bool:
        """Independently verify this trace-radical order enlargement."""
        try:
            prime = _normalize_base_prime(
                self.previous_order.extension,
                self.prime,
            )
            if prime != self.prime:
                return False
            if self.previous_order.extension != self.new_order.extension:
                return False
            if self.previous_discriminant != self.previous_order.discriminant:
                return False
            if self.new_discriminant != self.new_order.discriminant:
                return False
            if not self.new_order.contains_order(self.previous_order):
                return False
            if self.new_order.equivalent(self.previous_order):
                return False
            if self.index != self.new_order.index_of(self.previous_order):
                return False
            expected_idealizer = self.previous_order.idealizer(
                self.previous_order.trace_radical(prime)
            )
            return (
                self.new_order.equivalent(expected_idealizer)
                and self.verifies_discriminant_index_formula
            )
        except (NotImplementedError, TypeError, ValueError):
            return False


@dataclass(frozen=True, slots=True)
class OrderMaximalityCertificate:
    """One final ``prime``-maximality certificate."""

    order: AlgebraicOrder
    prime: Poly
    trace_radical: AlgebraicFractionalIdeal
    idealizer: AlgebraicOrder

    @property
    def verifies(self) -> bool:
        """Independently verify that the order is maximal at ``prime``."""
        try:
            prime = _normalize_base_prime(self.order.extension, self.prime)
            if prime != self.prime or self.trace_radical.order is not self.order:
                return False
            expected_radical = self.order.trace_radical(prime)
            if self.trace_radical != expected_radical:
                return False
            expected_idealizer = self.order.idealizer(expected_radical)
            return self.idealizer.equivalent(
                expected_idealizer
            ) and expected_idealizer.equivalent(self.order)
        except (NotImplementedError, TypeError, ValueError):
            return False


@dataclass(frozen=True, slots=True)
class IntegralClosureResult:
    """Certified maximal order and its trace-radical refinement history."""

    initial_order: AlgebraicOrder
    order: AlgebraicOrder
    steps: tuple[IntegralClosureStep, ...]
    tested_primes: tuple[Poly, ...]
    maximality_certificates: tuple[OrderMaximalityCertificate, ...]

    @property
    def changed(self) -> bool:
        """Whether the initial order required enlargement."""
        return bool(self.steps)

    @property
    def is_certified(self) -> bool:
        """Whether refinement and final prime-maximality checks all verify."""
        try:
            if self.initial_order.extension != self.order.extension:
                return False

            current = self.initial_order
            for step in self.steps:
                if not step.previous_order.equivalent(current) or not step.verifies:
                    return False
                current = step.new_order
            if not current.equivalent(self.order):
                return False

            _, factors = self.order.discriminant.factor_list()
            expected_primes = {
                factor.monic() for factor, multiplicity in factors if multiplicity >= 2
            }
            certified_primes = [
                certificate.prime for certificate in self.maximality_certificates
            ]
            if (
                len(certified_primes) != len(expected_primes)
                or set(certified_primes) != expected_primes
            ):
                return False
            return all(
                certificate.order.equivalent(self.order) and certificate.verifies
                for certificate in self.maximality_certificates
            )
        except (NotImplementedError, TypeError, ValueError):
            return False


def polynomial_order(extension: AlgebraicExtension) -> AlgebraicOrder:
    r"""Construct an integral power order from an arbitrary monic model.

    If the defining polynomial has rational-function coefficients, multiplying
    its generator by one common coefficient denominator produces an integral
    generator.  The resulting power basis is therefore a valid starting order
    for maximal-order refinement.
    """
    if not isinstance(extension, AlgebraicExtension):
        raise TypeError("a polynomial order requires an AlgebraicExtension")
    parent, constants, variable = _base_polynomial_ring(extension)
    coefficients = cast(
        tuple[FracElement, ...],
        tuple(
            parent.convert(extension.minimal_polynomial.nth(degree))
            for degree in range(extension.minimal_polynomial.degree())
        ),
    )
    denominator = _common_denominator(coefficients, constants, variable)
    denominator_element = _embed_parent(extension, denominator)
    integral_generator = extension.field.generator * denominator_element
    elements = tuple(integral_generator**power for power in range(extension.field.rank))
    return AlgebraicOrder(IntegralBasis(extension, elements))


def integral_closure(
    extension: AlgebraicExtension,
    *,
    initial_order: AlgebraicOrder | None = None,
    max_refinements: int = 256,
) -> IntegralClosureResult:
    r"""Compute the integral closure of ``C[x]`` in ``extension``.

    In characteristic zero, the radical of ``prime*order`` is the radical of
    the trace pairing modulo ``prime``.  The order is ``prime``-maximal exactly
    when the idealizer of that radical is the order itself.  Repeating strict
    idealizer enlargements over every prime whose square divides the
    discriminant terminates at the maximal order.
    """
    if not isinstance(extension, AlgebraicExtension):
        raise TypeError("integral closure requires an AlgebraicExtension")
    _, constants, _ = _base_polynomial_ring(extension)
    if constants.characteristic() != 0:
        raise NotImplementedError(
            "trace-radical maximal orders currently require characteristic zero"
        )
    if not isinstance(max_refinements, int) or max_refinements <= 0:
        raise ValueError("max_refinements must be a positive integer")

    current = polynomial_order(extension) if initial_order is None else initial_order
    if current.extension != extension:
        raise ValueError("the initial order belongs to a different extension")
    start = current
    steps: list[IntegralClosureStep] = []
    tested_primes: list[Poly] = []
    final_certificates: tuple[OrderMaximalityCertificate, ...] = ()

    while True:
        enlarged = False
        round_certificates: list[OrderMaximalityCertificate] = []
        _, factors = current.discriminant.factor_list()
        candidates = tuple(
            factor.monic() for factor, multiplicity in factors if multiplicity >= 2
        )
        for prime in candidates:
            tested_primes.append(prime)
            radical = current.trace_radical(prime)
            idealizer = current.idealizer(radical)
            if idealizer.equivalent(current):
                round_certificates.append(
                    OrderMaximalityCertificate(
                        order=current,
                        prime=prime,
                        trace_radical=radical,
                        idealizer=idealizer,
                    )
                )
                continue
            if len(steps) >= max_refinements:
                raise RuntimeError("maximal-order refinement exceeded max_refinements")
            if not idealizer.contains_order(current):
                raise ValueError("an idealizer failed to contain its source order")
            index = idealizer.index_of(current)
            step = IntegralClosureStep(
                prime=prime,
                previous_discriminant=current.discriminant,
                new_discriminant=idealizer.discriminant,
                index=index,
                previous_order=current,
                new_order=idealizer,
            )
            if not step.verifies_discriminant_index_formula:
                raise ValueError(
                    "order enlargement violated the discriminant-index identity"
                )
            steps.append(step)
            current = idealizer
            enlarged = True
            break
        if not enlarged:
            final_certificates = tuple(round_certificates)
            break

    result = IntegralClosureResult(
        initial_order=start,
        order=current,
        steps=tuple(steps),
        tested_primes=tuple(tested_primes),
        maximality_certificates=final_certificates,
    )
    if not result.is_certified:
        raise ValueError("maximal-order refinement certificate is inconsistent")
    return result


def _reduce_order_coordinates(
    order: AlgebraicOrder,
    element: object,
    context: _BaseResidueContext,
) -> tuple[object, ...]:
    return tuple(
        context.reduce_polynomial(coordinate)
        for coordinate in order.polynomial_coordinates(element)
    )


def _reduce_polynomial_matrix(
    matrix: DomainMatrix,
    context: _BaseResidueContext,
) -> DomainMatrix:
    variable = context.prime.gens[0]
    constants = context.prime.domain
    return DomainMatrix(
        [
            [
                context.reduce_polynomial(
                    Poly(
                        matrix.domain.to_sympy(entry),
                        variable,
                        domain=constants,
                    )
                )
                for entry in row
            ]
            for row in matrix.to_list()
        ],
        matrix.shape,
        context.field,
    )


@dataclass(frozen=True, slots=True)
class _SeparatorData:
    """A certified primitive element of the reduced residue algebra."""

    element: ExtensionElement
    symbol: Symbol
    characteristic_polynomial: Poly
    factors: tuple[tuple[Poly, int], ...]
    nilradical_rows: tuple[tuple[object, ...], ...]
    reduced_rank: int
    power_nilradical_inverse: DomainMatrix


def _separating_residue_element(
    order: AlgebraicOrder,
    context: _BaseResidueContext,
) -> _SeparatorData:
    trace_reduction = _reduce_polynomial_matrix(
        order.trace_pairing_matrix(),
        context,
    )
    nilradical_rows = tuple(tuple(row) for row in trace_reduction.nullspace().to_list())
    reduced_rank = order.rank - len(nilradical_rows)
    if reduced_rank <= 0:
        raise ValueError("the reduced residue algebra has zero dimension")

    symbol = Dummy("residue_generator")
    parent = order.extension.parent_field
    integer_vectors = (
        coefficients
        for bound in count(1)
        for coefficients in product(range(-bound, bound + 1), repeat=order.rank)
        if max(abs(coefficient) for coefficient in coefficients) == bound
    )
    for coefficients in integer_vectors:
        candidate = order.basis.element(
            tuple(parent.convert(coefficient) for coefficient in coefficients)
        )
        multiplication = _reduce_polynomial_matrix(
            order.multiplication_matrix(candidate),
            context,
        )
        characteristic_polynomial = Poly.from_list(
            multiplication.charpoly(),
            symbol,
            domain=context.field,
        )
        try:
            _, factor_list = characteristic_polynomial.factor_list()
        except NotImplementedError as exc:
            raise NotImplementedError(
                "SymPy could not factor the exact residue-algebra polynomial"
            ) from exc
        factors = tuple(
            (factor.monic(), multiplicity) for factor, multiplicity in factor_list
        )
        if sum(factor.degree() for factor, _ in factors) != reduced_rank:
            continue

        power_columns = tuple(
            _reduce_order_coordinates(
                order,
                candidate**power,
                context,
            )
            for power in range(reduced_rank)
        )
        nilradical_columns = tuple(tuple(row) for row in nilradical_rows)
        power_nilradical = _matrix_from_columns(
            power_columns + nilradical_columns,
            context.field,
        )
        try:
            power_nilradical_inverse = power_nilradical.inv()
        except DMNonInvertibleMatrixError:
            continue

        return _SeparatorData(
            element=candidate,
            symbol=symbol,
            characteristic_polynomial=characteristic_polynomial,
            factors=factors,
            nilradical_rows=nilradical_rows,
            reduced_rank=reduced_rank,
            power_nilradical_inverse=power_nilradical_inverse,
        )

    raise RuntimeError("failed to find a separating residue-algebra element")


def _residue_basis_images(
    order: AlgebraicOrder,
    context: _BaseResidueContext,
    separator: _SeparatorData,
    residue_polynomial: Poly,
) -> tuple[ExtensionElement, ...]:
    residue_field = FiniteExtension(residue_polynomial)
    inverse_rows = separator.power_nilradical_inverse.to_list()
    images = []
    for basis_index in range(order.rank):
        expression = sum(
            context.field.to_sympy(inverse_rows[power][basis_index])
            * separator.symbol**power
            for power in range(separator.reduced_rank)
        )
        images.append(
            cast(
                ExtensionElement,
                residue_field.from_sympy(expression),
            )
        )
    return tuple(images)


def _prime_ideal_from_residue_map(
    order: AlgebraicOrder,
    context: _BaseResidueContext,
    residue_polynomial: Poly,
    basis_images: tuple[ExtensionElement, ...],
) -> AlgebraicFractionalIdeal:
    relative_degree = residue_polynomial.degree()
    residue_field = basis_images[0].ext
    map_matrix = DomainMatrix(
        [
            [
                residue_field.domain.convert(image.rep.nth(power))
                for image in basis_images
            ]
            for power in range(relative_degree)
        ],
        (relative_degree, order.rank),
        context.field,
    )
    kernel_rows = map_matrix.nullspace().to_list()
    parent = cast(FractionField, order.extension.parent_field)
    prime_element = _embed_parent(order.extension, context.prime)
    generators: list[ExtensionElement] = [
        prime_element * basis_element for basis_element in order.basis.elements
    ]
    for kernel_row in kernel_rows:
        generators.append(
            order.basis.element(
                tuple(
                    _polynomial_parent_element(
                        context.lift(coefficient),
                        parent,
                    )
                    for coefficient in kernel_row
                )
            )
        )
    return AlgebraicFractionalIdeal(order, tuple(generators))


@dataclass(frozen=True, slots=True, eq=False)
class FiniteAlgebraicPlace:
    r"""A closed finite place represented in a certified maximal order."""

    order: AlgebraicOrder
    base_prime: Poly
    base_residue_field: Domain
    base_root: Expr
    separator: ExtensionElement
    residue_polynomial: Poly
    residue_field: FiniteExtension
    ramification_index: int
    prime_ideal: AlgebraicFractionalIdeal
    _context: _BaseResidueContext = dataclass_field(
        repr=False,
        compare=False,
    )
    _basis_images: tuple[ExtensionElement, ...] = dataclass_field(
        repr=False,
        compare=False,
    )
    _uniformizer_cache: ExtensionElement | None = dataclass_field(
        default=None,
        init=False,
        repr=False,
        compare=False,
    )
    _different_exponent_cache: int | None = dataclass_field(
        default=None,
        init=False,
        repr=False,
        compare=False,
    )
    _prime_power_cache: dict[int, AlgebraicFractionalIdeal] = dataclass_field(
        default_factory=dict,
        init=False,
        repr=False,
        compare=False,
    )

    @property
    def extension(self) -> AlgebraicExtension:
        """The algebraic function field containing this place."""
        return self.order.extension

    @property
    def base_degree(self) -> int:
        """Degree of the base point over the constant field."""
        return self.base_prime.degree()

    @property
    def relative_degree(self) -> int:
        """Residue degree over the selected base point."""
        return self.residue_polynomial.degree()

    @property
    def degree(self) -> int:
        """Residue-field degree over the original constant field."""
        return self.base_degree * self.relative_degree

    @property
    def is_ramified(self) -> bool:
        """Whether the place is ramified over the rational base."""
        return self.ramification_index > 1

    @property
    def uniformizer(self) -> ExtensionElement:
        """Return an exact element of valuation one."""
        cached = self._uniformizer_cache
        if cached is not None:
            return cached

        square = self._prime_power(2)
        for basis_element in self.prime_ideal.basis_elements:
            if not square.contains(basis_element):
                if self.valuation(basis_element) != 1:
                    raise ValueError("a prime-ideal generator failed valuation one")
                object.__setattr__(
                    self,
                    "_uniformizer_cache",
                    basis_element,
                )
                return basis_element
        raise ValueError("the prime ideal is indistinguishable from its square")

    @property
    def different_exponent(self) -> int:
        """Valuation of the relative different at this place."""
        cached = self._different_exponent_cache
        if cached is None:
            cached = self.ideal_valuation(self.order.different)
            object.__setattr__(self, "_different_exponent_cache", cached)
        return cached

    def _prime_power(self, exponent: int) -> AlgebraicFractionalIdeal:
        """Return a cached nonnegative power of this place's prime ideal."""
        if exponent < 0:
            raise ValueError("cached prime powers require a nonnegative exponent")
        cache = self._prime_power_cache
        if 0 not in cache:
            cache[0] = self.order.unit_ideal()
            cache[1] = self.prime_ideal
        if exponent not in cache:
            largest = max(power for power in cache if power < exponent)
            ideal = cache[largest]
            for power in range(largest + 1, exponent + 1):
                ideal = ideal.multiply(self.prime_ideal)
                cache[power] = ideal
        return cache[exponent]

    def reduce_integral(self, element: object) -> ExtensionElement:
        """Reduce an element of the maximal order into the residue field."""
        coordinates = self.order.polynomial_coordinates(element)
        result = self.residue_field.zero
        for coordinate, image in zip(
            coordinates,
            self._basis_images,
            strict=True,
        ):
            base_value = self._context.reduce_polynomial(coordinate)
            embedded_base_value = self.residue_field.from_sympy(
                self.base_residue_field.to_sympy(base_value)
            )
            result += embedded_base_value * image
        return cast(ExtensionElement, result)

    def lift_residue(self, value: object) -> ExtensionElement:
        """Lift a residue-field element to an element of the maximal order."""
        converted = self.residue_field.convert(value)
        parent = cast(FractionField, self.extension.parent_field)
        result = self.extension.field.zero
        for power in range(self.relative_degree - 1, -1, -1):
            result *= self.separator
            base_coefficient = converted.rep.nth(power)
            result += _embed_parent(
                self.extension,
                _polynomial_parent_element(
                    self._context.lift(base_coefficient),
                    parent,
                ),
            )
        if self.reduce_integral(result) != converted:
            raise ValueError("residue lifting failed to round-trip")
        return result

    def valuation(self, element: object) -> int | Expr:
        """Return the normalized discrete valuation, with ``v(0) = oo``."""
        value = _extension_element(self.extension, element)
        if value == self.extension.field.zero:
            return S.Infinity

        fraction = self.order.basis.fraction(value)
        parent = cast(FractionField, self.extension.parent_field)
        numerator = self.order.basis.element(
            tuple(
                _polynomial_parent_element(polynomial, parent)
                for polynomial in fraction.numerators
            )
        )
        denominator_order = _polynomial_multiplicity(
            fraction.denominator,
            self.base_prime,
        )
        uniformizer = self._uniformizer_cache
        if uniformizer is None:
            numerator_valuation = self._integral_element_valuation(numerator)
        else:
            numerator_valuation = self._regular_element_valuation(
                numerator,
                uniformizer,
            )
        return numerator_valuation - self.ramification_index * denominator_order

    def _integral_element_valuation(self, element: ExtensionElement) -> int:
        if not self.order.contains(element):
            raise ValueError("integral valuation requires an order element")
        if element == self.extension.field.zero:
            raise ValueError("the zero element has infinite valuation")
        exponent = 0
        while self._prime_power(exponent + 1).contains(element):
            exponent += 1
        return exponent

    def ideal_valuation(self, ideal: AlgebraicFractionalIdeal) -> int:
        """Return the exponent of this prime in a fractional ideal."""
        if ideal.order is not self.order:
            raise ValueError("ideal valuation requires the place's order")
        denominator, scaled = _integral_ideal_scale(ideal)
        return self._scaled_ideal_valuation(scaled, denominator)

    def _scaled_ideal_valuation(
        self,
        scaled: AlgebraicFractionalIdeal,
        denominator: Poly,
    ) -> int:
        """Value an ideal from a verified integral scalar multiple."""
        if scaled.order is not self.order or not scaled.is_integral:
            raise ValueError("ideal valuation requires an integral scaled ideal")
        denominator_order = _polynomial_multiplicity(
            denominator,
            self.base_prime,
        )
        exponent = 0
        while scaled.is_subset_of(self._prime_power(exponent + 1)):
            exponent += 1
        return exponent - self.ramification_index * denominator_order

    def reduce_local(self, element: object) -> ExtensionElement:
        """Reduce any element regular at this place."""
        value = _extension_element(self.extension, element)
        valuation = self.valuation(value)
        if valuation is S.Infinity:
            return self.residue_field.zero
        if cast(int, valuation) < 0:
            raise ValueError("an element with a pole has no residue-class value")
        return self._reduce_regular(value)

    def _reduce_regular(
        self,
        value: ExtensionElement,
    ) -> ExtensionElement:
        """Reduce an element already known to be regular at this place."""
        if value == self.extension.field.zero:
            return self.residue_field.zero
        if self.order.contains(value):
            return self.reduce_integral(value)

        denominator_ideal = self.order.unit_ideal().intersection(
            self.order.principal_ideal(self.extension.field.one / value)
        )
        for denominator in denominator_ideal.basis_elements:
            denominator_residue = self.reduce_integral(denominator)
            if denominator_residue == self.residue_field.zero:
                continue
            numerator = denominator * value
            if not self.order.contains(numerator):
                raise ValueError("a local denominator failed to clear the element")
            return self.reduce_integral(numerator) / denominator_residue
        raise ValueError("no denominator outside the place was found")

    def _regular_element_valuation(
        self,
        value: ExtensionElement,
        uniformizer: ExtensionElement,
    ) -> int:
        """Value a regular nonzero element by repeated residue extraction."""
        if value == self.extension.field.zero:
            raise ValueError("the zero element has infinite valuation")
        exponent = 0
        quotient = value
        while self._reduce_regular(quotient) == self.residue_field.zero:
            exponent += 1
            quotient /= uniformizer
        return exponent

    def local_expansion(
        self,
        element: object,
        *,
        stop: int,
    ) -> LocalLaurentExpansion:
        """Expand through powers strictly below ``stop`` in a uniformizer."""
        if not isinstance(stop, int):
            raise TypeError("the local expansion stop must be an integer")
        value = _extension_element(self.extension, element)
        if value == self.extension.field.zero:
            return LocalLaurentExpansion(
                place=self,
                element=value,
                start=stop,
                stop=stop,
                coefficients=(),
                remainder=value,
                remainder_valuation=S.Infinity,
            )
        uniformizer = self.uniformizer
        initial_valuation = self.valuation(value)
        start = cast(int, initial_valuation)
        if stop <= start:
            return LocalLaurentExpansion(
                place=self,
                element=value,
                start=start,
                stop=stop,
                coefficients=(),
                remainder=value,
                remainder_valuation=start,
            )

        uniformizer_power = uniformizer**start
        remainder = value
        coefficients: list[ExtensionElement] = []
        for _ in range(start, stop):
            coefficient = self._reduce_regular(remainder / uniformizer_power)
            if coefficient != self.residue_field.zero:
                remainder -= self.lift_residue(coefficient) * uniformizer_power
            coefficients.append(coefficient)
            uniformizer_power *= uniformizer

        final_valuation = self.valuation(remainder)
        expansion = LocalLaurentExpansion(
            place=self,
            element=value,
            start=start,
            stop=stop,
            coefficients=tuple(coefficients),
            remainder=remainder,
            remainder_valuation=final_valuation,
        )
        if not expansion.reconstructs or (
            final_valuation is not S.Infinity and cast(int, final_valuation) < stop
        ):
            raise ValueError("local expansion failed its exact remainder invariant")
        return expansion

    def differential_residue(self, coefficient: object) -> ExtensionElement:
        r"""Return the residue of ``coefficient*dx`` at this place."""
        value = _extension_element(self.extension, coefficient)
        if value == self.extension.field.zero:
            return self.residue_field.zero
        uniformizer_derivative = _standard_derivative(
            self.extension,
            self.uniformizer,
        )
        local_coefficient = value / uniformizer_derivative
        valuation = self.valuation(local_coefficient)
        if valuation is S.Infinity or cast(int, valuation) > -1:
            return self.residue_field.zero
        expansion = self.local_expansion(local_coefficient, stop=0)
        return expansion.coefficient(-1)


def _polynomial_multiplicity(polynomial: Poly, prime: Poly) -> int:
    exponent = 0
    remainder = polynomial
    while remainder.degree() >= prime.degree():
        quotient, residue = remainder.div(prime)
        if not residue.is_zero:
            break
        exponent += 1
        remainder = quotient
    return exponent


def _parent_prime_support(
    element: FracElement,
    extension: AlgebraicExtension,
) -> tuple[Poly, ...]:
    _, constants, variable = _base_polynomial_ring(extension)
    numerator = Poly.from_dict(
        element.numer.to_dict(),
        variable,
        domain=constants,
    )
    denominator = Poly.from_dict(
        element.denom.to_dict(),
        variable,
        domain=constants,
    )
    primes: dict[Poly, None] = {}
    for polynomial in (numerator, denominator):
        _, factors = polynomial.factor_list()
        for factor, _ in factors:
            primes[factor.monic()] = None
    return tuple(primes)


def _polynomial_prime_support(polynomial: Poly) -> tuple[Poly, ...]:
    """Return the monic irreducible factors of a nonzero polynomial."""
    if polynomial.is_zero:
        raise ValueError("zero has every base prime in its support")
    _, factors = polynomial.factor_list()
    return tuple(factor.monic() for factor, _ in factors)


def _merge_prime_supports(
    *supports: tuple[Poly, ...],
) -> tuple[Poly, ...]:
    """Merge prime-support tuples without losing deterministic order."""
    primes: dict[Poly, None] = {}
    for support in supports:
        for prime in support:
            primes[prime] = None
    return tuple(primes)


def _element_base_prime_support(
    order: AlgebraicOrder,
    element: ExtensionElement,
) -> tuple[Poly, ...]:
    """Find finite base support without norm cancellation across places."""
    fraction = order.basis.fraction(element)
    parent = cast(FractionField, order.extension.parent_field)
    integral_numerator = order.basis.element(
        tuple(
            _polynomial_parent_element(polynomial, parent)
            for polynomial in fraction.numerators
        )
    )
    numerator_norm = cast(
        FracElement,
        order.extension.norm(integral_numerator),
    )
    return _merge_prime_supports(
        _parent_prime_support(numerator_norm, order.extension),
        _polynomial_prime_support(fraction.denominator),
    )


def _integral_ideal_scale(
    ideal: AlgebraicFractionalIdeal,
) -> tuple[Poly, AlgebraicFractionalIdeal]:
    """Clear all coordinate denominators of a fractional ideal."""
    _, constants, variable = _base_polynomial_ring(ideal.order.extension)
    entries = tuple(
        cast(FracElement, entry)
        for row in ideal.coordinate_matrix.to_list()
        for entry in row
    )
    denominator = _common_denominator(entries, constants, variable)
    scaled = ideal.scale(_embed_parent(ideal.order.extension, denominator))
    if not scaled.is_integral:
        raise ValueError("common-denominator scaling did not make an ideal integral")
    return denominator, scaled


def _fractional_ideal_base_prime_support(
    ideal: AlgebraicFractionalIdeal,
    denominator: Poly,
    scaled: AlgebraicFractionalIdeal,
) -> tuple[Poly, ...]:
    """Find finite support from an integral scalar multiple of an ideal."""
    determinant = cast(FracElement, scaled.coordinate_matrix.det())
    return _merge_prime_supports(
        _parent_prime_support(determinant, ideal.order.extension),
        _polynomial_prime_support(denominator),
    )


def _standard_derivative(
    extension: AlgebraicExtension,
    element: object,
) -> ExtensionElement:
    parent, _, variable = _base_polynomial_ring(extension)

    def differentiate_parent(value: object) -> FieldElement:
        converted = parent.convert(value)
        return cast(
            FieldElement,
            parent.from_sympy(parent.to_sympy(converted).diff(variable)),
        )

    return cast(
        ExtensionElement,
        extension.differentiate(
            _extension_element(extension, element),
            differentiate_parent,
        ),
    )


@dataclass(frozen=True, slots=True)
class LocalLaurentExpansion:
    """A certified finite segment of a local Laurent expansion."""

    place: FiniteAlgebraicPlace | InfiniteAlgebraicPlace
    element: ExtensionElement
    start: int
    stop: int
    coefficients: tuple[ExtensionElement, ...]
    remainder: ExtensionElement
    remainder_valuation: int | Expr

    def coefficient(self, exponent: int) -> ExtensionElement:
        """Return a known coefficient, rejecting uncomputed tail terms."""
        if not isinstance(exponent, int):
            raise TypeError("a Laurent exponent must be an integer")
        if exponent < self.start:
            return self.place.residue_field.zero
        if self.start <= exponent < self.stop:
            return self.coefficients[exponent - self.start]
        if self.remainder_valuation is S.Infinity:
            return self.place.residue_field.zero
        raise IndexError(
            f"coefficient {exponent} was not computed; "
            f"the expansion stops before {self.stop}"
        )

    @property
    def reconstructs(self) -> bool:
        """Whether the truncated terms plus remainder reproduce the input."""
        reconstructed = self.remainder
        uniformizer = self.place.uniformizer
        for offset, coefficient in enumerate(self.coefficients):
            exponent = self.start + offset
            reconstructed += (
                self.place.lift_residue(coefficient) * uniformizer**exponent
            )
        return reconstructed == self.element


def _decompose_finite_places(
    order: AlgebraicOrder,
    prime: Poly,
) -> tuple[FiniteAlgebraicPlace, ...]:
    context = _BaseResidueContext.create(order.extension, prime)
    separator = _separating_residue_element(order, context)
    places = []
    for residue_polynomial, ramification_index in separator.factors:
        basis_images = _residue_basis_images(
            order,
            context,
            separator,
            residue_polynomial,
        )
        prime_ideal = _prime_ideal_from_residue_map(
            order,
            context,
            residue_polynomial,
            basis_images,
        )
        residue_field = basis_images[0].ext
        place = FiniteAlgebraicPlace(
            order=order,
            base_prime=context.prime,
            base_residue_field=context.field,
            base_root=context.root,
            separator=separator.element,
            residue_polynomial=residue_polynomial,
            residue_field=residue_field,
            ramification_index=ramification_index,
            prime_ideal=prime_ideal,
            _context=context,
            _basis_images=basis_images,
        )
        if place.valuation(_embed_parent(order.extension, context.prime)) != (
            ramification_index
        ):
            raise ValueError("base-prime valuation disagrees with ramification")
        places.append(place)

    if (
        sum(place.ramification_index * place.relative_degree for place in places)
        != order.rank
    ):
        raise ValueError("finite-place degrees violate the fundamental identity")
    return tuple(places)


@dataclass(frozen=True, slots=True)
class ReciprocalFunctionField:
    """A reciprocal chart used to represent every place at infinity."""

    original_extension: AlgebraicExtension
    variable: Symbol
    scale_exponent: int
    extension: AlgebraicExtension
    closure: IntegralClosureResult

    @classmethod
    def create(
        cls,
        extension: AlgebraicExtension,
        variable: Symbol | None = None,
    ) -> ReciprocalFunctionField:
        parent, constants, base_variable = _base_polynomial_ring(extension)
        reciprocal_variable = Dummy("s") if variable is None else variable
        if not isinstance(reciprocal_variable, Symbol):
            raise TypeError("the reciprocal variable must be a Symbol")
        if reciprocal_variable in {
            base_variable,
            extension.generator,
        } | set(getattr(constants, "symbols", ())):
            raise ValueError("the reciprocal variable must be new")
        reciprocal_parent = constants.frac_field(reciprocal_variable)
        degree = extension.field.rank
        scale_exponent = 0
        for power in range(degree):
            coefficient = cast(
                FracElement,
                parent.convert(extension.minimal_polynomial.nth(power)),
            )
            if not coefficient:
                continue
            numerator = Poly.from_dict(
                coefficient.numer.to_dict(),
                base_variable,
                domain=constants,
            )
            denominator = Poly.from_dict(
                coefficient.denom.to_dict(),
                base_variable,
                domain=constants,
            )
            pole_order = max(0, numerator.degree() - denominator.degree())
            exponent_gap = degree - power
            scale_exponent = max(
                scale_exponent,
                (pole_order + exponent_gap - 1) // exponent_gap,
            )

        reciprocal_generator = Dummy("z")
        defining_expression = reciprocal_generator**degree
        for power in range(degree):
            coefficient = parent.to_sympy(extension.minimal_polynomial.nth(power))
            transformed = coefficient.subs(
                base_variable,
                1 / reciprocal_variable,
            ) * reciprocal_variable ** (scale_exponent * (degree - power))
            defining_expression += transformed * reciprocal_generator**power
        reciprocal_extension = AlgebraicExtension(
            Poly(
                defining_expression,
                reciprocal_generator,
                domain=reciprocal_parent,
            )
        )
        closure = integral_closure(reciprocal_extension)
        return cls(
            original_extension=extension,
            variable=reciprocal_variable,
            scale_exponent=scale_exponent,
            extension=reciprocal_extension,
            closure=closure,
        )

    def forward(self, element: object) -> ExtensionElement:
        """Map an original field element into the reciprocal chart."""
        original = _extension_element(self.original_extension, element)
        original_parent, _, original_variable = _base_polynomial_ring(
            self.original_extension
        )
        expression = 0
        for power in range(self.original_extension.field.rank):
            coefficient = original_parent.to_sympy(original.rep.nth(power))
            expression += (
                coefficient.subs(
                    original_variable,
                    1 / self.variable,
                )
                * (self.extension.generator / self.variable**self.scale_exponent)
                ** power
            )
        return cast(
            ExtensionElement,
            self.extension.field.from_sympy(expression),
        )

    def backward(self, element: object) -> ExtensionElement:
        """Map a reciprocal-chart element back to the original field."""
        reciprocal = _extension_element(self.extension, element)
        _, _, original_variable = _base_polynomial_ring(self.original_extension)
        reciprocal_parent = cast(FractionField, self.extension.parent_field)
        expression = 0
        for power in range(self.extension.field.rank):
            coefficient = reciprocal_parent.to_sympy(reciprocal.rep.nth(power))
            expression += (
                coefficient.subs(
                    self.variable,
                    1 / original_variable,
                )
                * (
                    self.original_extension.generator
                    / original_variable**self.scale_exponent
                )
                ** power
            )
        return cast(
            ExtensionElement,
            self.original_extension.field.from_sympy(expression),
        )


@dataclass(frozen=True, slots=True, eq=False)
class InfiniteAlgebraicPlace:
    """A closed place at infinity represented on a reciprocal chart."""

    chart: ReciprocalFunctionField
    finite_place: FiniteAlgebraicPlace

    @property
    def extension(self) -> AlgebraicExtension:
        """The original algebraic function field."""
        return self.chart.original_extension

    @property
    def residue_field(self) -> FiniteExtension:
        """Exact residue field."""
        return self.finite_place.residue_field

    @property
    def degree(self) -> int:
        """Residue-field degree over the constant field."""
        return self.finite_place.degree

    @property
    def relative_degree(self) -> int:
        """Residue degree over the rational point at infinity."""
        return self.finite_place.relative_degree

    @property
    def ramification_index(self) -> int:
        """Ramification index above infinity."""
        return self.finite_place.ramification_index

    @property
    def is_ramified(self) -> bool:
        """Whether infinity is ramified."""
        return self.finite_place.is_ramified

    @property
    def uniformizer(self) -> ExtensionElement:
        """Return a valuation-one element in the original field."""
        return self.chart.backward(self.finite_place.uniformizer)

    @property
    def different_exponent(self) -> int:
        """Valuation of the relative different at infinity."""
        return self.finite_place.different_exponent

    def valuation(self, element: object) -> int | Expr:
        """Normalized valuation in the original field."""
        return self.finite_place.valuation(self.chart.forward(element))

    def reduce_local(self, element: object) -> ExtensionElement:
        """Reduce an original-field element regular at infinity."""
        return self.finite_place.reduce_local(self.chart.forward(element))

    def lift_residue(self, value: object) -> ExtensionElement:
        """Lift a residue value into the original field."""
        return self.chart.backward(self.finite_place.lift_residue(value))

    def local_expansion(
        self,
        element: object,
        *,
        stop: int,
    ) -> LocalLaurentExpansion:
        """Compute a Laurent segment at infinity."""
        value = _extension_element(self.extension, element)
        reciprocal_expansion = self.finite_place.local_expansion(
            self.chart.forward(value),
            stop=stop,
        )
        return LocalLaurentExpansion(
            place=self,
            element=value,
            start=reciprocal_expansion.start,
            stop=reciprocal_expansion.stop,
            coefficients=reciprocal_expansion.coefficients,
            remainder=self.chart.backward(reciprocal_expansion.remainder),
            remainder_valuation=reciprocal_expansion.remainder_valuation,
        )

    def differential_residue(self, coefficient: object) -> ExtensionElement:
        r"""Return the residue of ``coefficient*dx`` at infinity."""
        transformed = self.chart.forward(coefficient)
        reciprocal_base = _embed_parent(
            self.chart.extension,
            Poly(
                self.chart.variable,
                self.chart.variable,
                domain=_base_polynomial_ring(self.chart.extension)[1],
            ),
        )
        return self.finite_place.differential_residue(-transformed / reciprocal_base**2)


class AlgebraicFunctionField:
    r"""Certified global model for one finite extension of ``C(x)``."""

    def __init__(
        self,
        extension: AlgebraicExtension,
        *,
        closure: IntegralClosureResult | None = None,
        infinity_variable: Symbol | None = None,
    ) -> None:
        if not isinstance(extension, AlgebraicExtension):
            raise TypeError("an algebraic function field needs an extension")
        computed_closure = integral_closure(extension) if closure is None else closure
        if computed_closure.order.extension != extension:
            raise ValueError("the maximal-order certificate is for another field")
        if not computed_closure.is_certified:
            raise ValueError("the finite maximal order is not certified")
        self.extension = extension
        self.closure = computed_closure
        self.order = computed_closure.order
        self._infinity_variable = infinity_variable
        self._finite_cache: dict[Poly, tuple[FiniteAlgebraicPlace, ...]] = {}
        self._reciprocal_chart: ReciprocalFunctionField | None = None
        self._infinite_cache: tuple[InfiniteAlgebraicPlace, ...] | None = None

    def finite_places(
        self,
        base_prime: Poly,
    ) -> tuple[FiniteAlgebraicPlace, ...]:
        """Return every closed place above an irreducible finite base prime."""
        prime = _normalize_base_prime(self.extension, base_prime)
        places = self._finite_cache.get(prime)
        if places is None:
            places = _decompose_finite_places(self.order, prime)
            self._finite_cache[prime] = places
        return places

    @property
    def reciprocal_chart(self) -> ReciprocalFunctionField:
        """Reciprocal model used for the points at infinity."""
        if self._reciprocal_chart is None:
            self._reciprocal_chart = ReciprocalFunctionField.create(
                self.extension,
                self._infinity_variable,
            )
        return self._reciprocal_chart

    def infinite_places(self) -> tuple[InfiniteAlgebraicPlace, ...]:
        """Return every closed place over the point at infinity."""
        if self._infinite_cache is None:
            chart = self.reciprocal_chart
            _, constants, variable = _base_polynomial_ring(chart.extension)
            reciprocal_prime = Poly(variable, variable, domain=constants)
            finite_places = _decompose_finite_places(
                chart.closure.order,
                reciprocal_prime,
            )
            self._infinite_cache = tuple(
                InfiniteAlgebraicPlace(chart, place) for place in finite_places
            )
        return self._infinite_cache

    def principal_divisor(self, element: object) -> AlgebraicDivisor:
        """Return the complete divisor of a nonzero field element."""
        value = _extension_element(self.extension, element)
        if value == self.extension.field.zero:
            raise ValueError("the zero element has no principal divisor")

        terms: list[tuple[AlgebraicPlace, int]] = []
        for prime in _element_base_prime_support(self.order, value):
            for place in self.finite_places(prime):
                valuation = place.valuation(value)
                if valuation is S.Infinity:
                    raise ValueError("a nonzero element had infinite valuation")
                if valuation:
                    terms.append((place, cast(int, valuation)))
        for place in self.infinite_places():
            valuation = place.valuation(value)
            if valuation is S.Infinity:
                raise ValueError("a nonzero element had infinite valuation")
            if valuation:
                terms.append((place, cast(int, valuation)))

        divisor = AlgebraicDivisor(self, tuple(terms))
        if divisor.degree != 0:
            raise ValueError("a principal divisor failed the degree-zero identity")
        return divisor

    def ideal_divisor(
        self,
        ideal: AlgebraicFractionalIdeal,
    ) -> AlgebraicDivisor:
        """Factor a fractional ideal into its finite-place divisor."""
        if ideal.order is not self.order:
            raise ValueError("ideal factorization requires the model's maximal order")
        denominator, scaled = _integral_ideal_scale(ideal)
        terms: list[tuple[AlgebraicPlace, int]] = []
        for prime in _fractional_ideal_base_prime_support(
            ideal,
            denominator,
            scaled,
        ):
            for place in self.finite_places(prime):
                valuation = place._scaled_ideal_valuation(
                    scaled,
                    denominator,
                )
                if valuation:
                    terms.append((place, valuation))
        return AlgebraicDivisor(self, tuple(terms))

    def finite_ideal(
        self,
        divisor: AlgebraicDivisor,
    ) -> AlgebraicFractionalIdeal:
        """Convert a divisor with finite support into a fractional ideal."""
        if not isinstance(divisor, AlgebraicDivisor):
            raise TypeError("finite ideal construction requires a divisor")
        if divisor.model is not self:
            raise ValueError("the divisor belongs to another global model")
        if any(isinstance(place, InfiniteAlgebraicPlace) for place, _ in divisor.terms):
            raise ValueError("a finite-order ideal cannot encode infinity support")

        result = self.order.unit_ideal()
        for place, coefficient in divisor.terms:
            if not isinstance(place, FiniteAlgebraicPlace):
                raise TypeError("finite divisor support has an invalid place")
            result = result.multiply(place.prime_ideal.power(coefficient))
        if self.ideal_divisor(result) != divisor:
            raise ValueError("finite divisor-to-ideal conversion failed to round-trip")
        return result

    def canonical_divisor(self) -> AlgebraicDivisor:
        r"""Return the divisor of ``dx`` via the relative different."""
        terms: list[tuple[AlgebraicPlace, int]] = []
        _, factors = self.order.discriminant.factor_list()
        for prime, _ in factors:
            for place in self.finite_places(prime.monic()):
                exponent = place.different_exponent
                if exponent:
                    terms.append((place, exponent))
        for place in self.infinite_places():
            exponent = place.different_exponent - 2 * place.ramification_index
            if exponent:
                terms.append((place, exponent))
        return AlgebraicDivisor(self, tuple(terms))

    @property
    def genus(self) -> int:
        """Genus obtained from the degree of a canonical divisor."""
        canonical_degree = self.canonical_divisor().degree
        if (canonical_degree + 2) % 2:
            raise ValueError("the canonical divisor has impossible odd degree")
        genus = (canonical_degree + 2) // 2
        if genus < 0:
            raise ValueError("the canonical divisor gives a negative genus")
        return genus

    def differential(self, coefficient: object) -> AlgebraicDifferential:
        """Construct the differential ``coefficient*dx``."""
        return AlgebraicDifferential(self, coefficient)


AlgebraicPlace = FiniteAlgebraicPlace | InfiniteAlgebraicPlace


@dataclass(frozen=True, slots=True, eq=False)
class AlgebraicDivisor:
    """An immutable formal integer sum of model-owned closed places."""

    model: AlgebraicFunctionField
    terms: tuple[tuple[AlgebraicPlace, int], ...] = ()

    def __post_init__(self) -> None:
        combined: dict[AlgebraicPlace, int] = {}
        order: list[AlgebraicPlace] = []
        for place, coefficient in self.terms:
            if not isinstance(
                place,
                (FiniteAlgebraicPlace, InfiniteAlgebraicPlace),
            ):
                raise TypeError("divisor support must consist of algebraic places")
            if place.extension != self.model.extension:
                raise ValueError("a divisor place belongs to another function field")
            if (
                isinstance(place, FiniteAlgebraicPlace)
                and place.order is not self.model.order
            ):
                raise ValueError("a finite place belongs to another global model")
            if (
                isinstance(place, InfiniteAlgebraicPlace)
                and place.chart is not self.model.reciprocal_chart
            ):
                raise ValueError("an infinite place belongs to another global model")
            if not isinstance(coefficient, int):
                raise TypeError("divisor coefficients must be integers")
            if place not in combined:
                order.append(place)
                combined[place] = 0
            combined[place] += coefficient
        object.__setattr__(
            self,
            "terms",
            tuple((place, combined[place]) for place in order if combined[place]),
        )

    @property
    def support(self) -> tuple[AlgebraicPlace, ...]:
        """Places with nonzero coefficient."""
        return tuple(place for place, _ in self.terms)

    @property
    def degree(self) -> int:
        """Weighted divisor degree over the constant field."""
        return sum(coefficient * place.degree for place, coefficient in self.terms)

    @property
    def is_zero(self) -> bool:
        """Whether the divisor has empty support."""
        return not self.terms

    @property
    def is_effective(self) -> bool:
        """Whether every coefficient is nonnegative."""
        return all(coefficient >= 0 for _, coefficient in self.terms)

    def coefficient(self, place: AlgebraicPlace) -> int:
        """Coefficient at one place."""
        return next(
            (
                coefficient
                for supported_place, coefficient in self.terms
                if supported_place is place
            ),
            0,
        )

    def add(self, other: AlgebraicDivisor) -> AlgebraicDivisor:
        """Divisor addition."""
        self._require_same_model(other)
        return AlgebraicDivisor(self.model, self.terms + other.terms)

    def __add__(self, other: AlgebraicDivisor) -> AlgebraicDivisor:
        return self.add(other)

    def __neg__(self) -> AlgebraicDivisor:
        return AlgebraicDivisor(
            self.model,
            tuple((place, -coefficient) for place, coefficient in self.terms),
        )

    def __sub__(self, other: AlgebraicDivisor) -> AlgebraicDivisor:
        return self.add(-other)

    def scale(self, coefficient: int) -> AlgebraicDivisor:
        """Multiply every divisor coefficient by an integer."""
        if not isinstance(coefficient, int):
            raise TypeError("a divisor scalar must be an integer")
        return AlgebraicDivisor(
            self.model,
            tuple(
                (place, coefficient * place_coefficient)
                for place, place_coefficient in self.terms
            ),
        )

    @property
    def positive_part(self) -> AlgebraicDivisor:
        """Effective positive part."""
        return AlgebraicDivisor(
            self.model,
            tuple(
                (place, coefficient)
                for place, coefficient in self.terms
                if coefficient > 0
            ),
        )

    @property
    def negative_part(self) -> AlgebraicDivisor:
        """Effective pole part, with signs reversed."""
        return AlgebraicDivisor(
            self.model,
            tuple(
                (place, -coefficient)
                for place, coefficient in self.terms
                if coefficient < 0
            ),
        )

    def _require_same_model(self, other: AlgebraicDivisor) -> None:
        if not isinstance(other, AlgebraicDivisor):
            raise TypeError("divisor arithmetic needs another divisor")
        if other.model is not self.model:
            raise ValueError("divisors must belong to the same global model")

    def __eq__(self, other: object) -> bool:
        if not isinstance(other, AlgebraicDivisor):
            return NotImplemented
        if other.model is not self.model:
            return False
        return all(
            self.coefficient(place) == coefficient for place, coefficient in other.terms
        ) and all(
            other.coefficient(place) == coefficient for place, coefficient in self.terms
        )


@dataclass(frozen=True, slots=True)
class AlgebraicDifferential:
    r"""A differential represented globally as ``coefficient*dx``.

    The private caches memoize exact divisor and local-residue computations.
    They are not part of the mathematical value or equality; they let a
    collector validate the data it just computed without repeating expensive
    global and local algebra.
    """

    model: AlgebraicFunctionField
    coefficient: object
    _divisor_cache: AlgebraicDivisor | None = dataclass_field(
        init=False,
        default=None,
        repr=False,
        compare=False,
    )
    _residue_cache: tuple[tuple[AlgebraicPlace, ExtensionElement], ...] = (
        dataclass_field(
            init=False,
            default=(),
            repr=False,
            compare=False,
        )
    )

    def __post_init__(self) -> None:
        object.__setattr__(
            self,
            "coefficient",
            _extension_element(self.model.extension, self.coefficient),
        )

    def order_at(self, place: AlgebraicPlace) -> int | Expr:
        """Order of the differential at one finite or infinite place."""
        if place.extension != self.model.extension:
            raise ValueError("the place belongs to another function field")
        valuation = place.valuation(self.coefficient)
        if valuation is S.Infinity:
            return S.Infinity
        if isinstance(place, FiniteAlgebraicPlace):
            return cast(int, valuation) + place.different_exponent
        return (
            cast(int, valuation)
            + place.different_exponent
            - 2 * place.ramification_index
        )

    def residue(self, place: AlgebraicPlace) -> ExtensionElement:
        """Exact local residue in the place's residue field."""
        if place.extension != self.model.extension:
            raise ValueError("the place belongs to another function field")
        for cached_place, cached_value in self._residue_cache:
            if place is cached_place:
                return cached_value
        value = place.differential_residue(self.coefficient)
        object.__setattr__(
            self,
            "_residue_cache",
            (*self._residue_cache, (place, value)),
        )
        return value

    def divisor(self) -> AlgebraicDivisor:
        """Complete divisor of this nonzero differential."""
        if self.coefficient == self.model.extension.field.zero:
            raise ValueError("the zero differential has no finite divisor")
        if self._divisor_cache is not None:
            return self._divisor_cache
        divisor = (
            self.model.principal_divisor(self.coefficient)
            + self.model.canonical_divisor()
        )
        object.__setattr__(self, "_divisor_cache", divisor)
        return divisor
