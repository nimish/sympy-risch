r"""Exact algebraic-curve infrastructure over a rational function field.

This module supplies the commutative-algebra layer that SymPy's exact finite
extensions do not currently provide for algebraic function fields:

* certified ``K[x]`` orders and maximal-order computation;
* full-rank fractional-ideal arithmetic over those orders;
* closed finite and infinite places, including ramification;
* exact discrete valuations, uniformizers, and local Laurent coefficients;
* divisors, principal divisors, differents, canonical divisors, and
  algebraic differentials.

The implementation deliberately stops before the algebraic Risch algorithms.
In particular, it does not solve principal-divisor or torsion-divisor
problems, reconstruct logarithmic terms, or solve a Risch differential
equation on the curve.

The current coefficient contract is a characteristic-zero exact field for
which SymPy can factor univariate polynomials after adjoining an algebraic
root.  The function field itself is one finite separable extension of
``C(x)``.
"""

